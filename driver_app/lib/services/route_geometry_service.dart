  /// Returns cached road segment or fallback geometry preferring main roads/highways
  List<LatLng> getSegment(int fromSeq, int toSeq) {
    if (toSeq <= fromSeq) {
      if (fromSeq == toSeq) {
        if (toSeq > 1) return getSegment(toSeq - 1, toSeq);
        return getSegment(6, 7);
      }
      return [];
    }
    final key = '$fromSeq-$toSeq';
    final cached = _cachedSegments[key];
    if (cached != null && cached.length > 2) return cached;
    if (_fallbackSegments.containsKey(key)) return _fallbackSegments[key]!;

    // Multi-segment chain: stitch consecutive segments between fromSeq and toSeq
    final chained = <LatLng>[];
    for (int s = fromSeq; s < toSeq; s++) {
      final sub = getSegment(s, s + 1);
      if (sub.isNotEmpty) {
        if (chained.isNotEmpty) {
          chained.addAll(sub.skip(1));
        } else {
          chained.addAll(sub);
        }
      }
    }
    return chained;
  }

  /// Returns continuous road geometry for the full circular route following main highways/roads
  List<LatLng> getFullRoute(List<dynamic> stops, {Iterable<int> skippedSequences = const []}) {
    if (stops.length < 2) return [];
    final points = <LatLng>[];
    final skippedSet = skippedSequences.toSet();

    for (int i = 0; i < stops.length - 1; i++) {
      final from = stops[i] is Map ? stops[i] as Map : {};
      final to = stops[i + 1] is Map ? stops[i + 1] as Map : {};

      final fromSeq = (from['sequence'] as num?)?.toInt() ?? (i + 1);
      final toSeq = (to['sequence'] as num?)?.toInt() ?? (i + 2);

      if (skippedSet.contains(fromSeq) || skippedSet.contains(toSeq)) {
        continue;
      }
      final seg = getSegment(fromSeq, toSeq);
      if (seg.isNotEmpty) {
        if (points.isNotEmpty) {
          points.addAll(seg.skip(1));
        } else {
          points.addAll(seg);
        }
      }
    }
    return points;
  }

  /// Returns active route from current bus position -> remaining road geometry to next stop
  List<LatLng> getActiveRoute({
    required LatLng? busPos,
    required int fromSeq,
    required int toSeq,
  }) {
    int effectiveFrom = fromSeq;
    int effectiveTo = toSeq;

    List<LatLng> segment;
    if (effectiveTo <= 1) {
      final stop1 = _fallbackSegments['1-2']?.first ?? const LatLng(23.82680318, 78.77196191);
      if (busPos != null) {
        final distToStop1 = const Distance().as(LengthUnit.Meter, busPos, stop1);
        if (distToStop1 <= 100) {
          // Bus is at/near Stop 1 preparing/departing towards Stop 2
          segment = getSegment(1, 2);
        } else {
          // Bus is approaching Stop 1 from circular route
          segment = getSegment(6, 7);
        }
      } else {
        segment = getSegment(1, 2);
      }
    } else {
      if (effectiveFrom >= effectiveTo) {
        effectiveFrom = effectiveTo - 1;
      }
      segment = getSegment(effectiveFrom, effectiveTo);
    }

    if (segment.isEmpty) {
      return busPos != null ? [busPos] : [];
    }

    if (busPos == null) {
      return segment;
    }

    return _sliceRouteFromBus(busPos, segment);
  }

  List<LatLng> _sliceRouteFromBus(LatLng busPos, List<LatLng> points) {
    if (points.length < 2) {
      return [busPos, ...points];
    }

    const dLatScale = 111000.0;
    final cosLat = math.cos(busPos.latitude * math.pi / 180.0) * 111000.0;
    final bx = busPos.longitude * cosLat;
    final by = busPos.latitude * dLatScale;

    int bestEdgeIdx = 0;
    double minDistanceSq = double.infinity;
    double bestT = 0.0;
    LatLng bestProjPoint = points[0];

    for (int i = 0; i < points.length - 1; i++) {
      final p1 = points[i];
      final p2 = points[i + 1];

      final x1 = p1.longitude * cosLat;
      final y1 = p1.latitude * dLatScale;
      final x2 = p2.longitude * cosLat;
      final y2 = p2.latitude * dLatScale;

      final dx = x2 - x1;
      final dy = y2 - y1;
      final lenSq = dx * dx + dy * dy;

      double t;
      if (lenSq < 1e-6) {
        t = 0.0;
      } else {
        t = ((bx - x1) * dx + (by - y1) * dy) / lenSq;
        if (t < 0.0) t = 0.0;
        if (t > 1.0) t = 1.0;
      }

      final projX = x1 + t * dx;
      final projY = y1 + t * dy;
      final distSq = (bx - projX) * (bx - projX) + (by - projY) * (by - projY);

      if (distSq < minDistanceSq) {
        minDistanceSq = distSq;
        bestEdgeIdx = i;
        bestT = t;
        bestProjPoint = LatLng(
          p1.latitude + t * (p2.latitude - p1.latitude),
          p1.longitude + t * (p2.longitude - p1.longitude),
        );
      }
    }

    final remaining = <LatLng>[busPos];
    if (bestEdgeIdx == 0 && bestT <= 0.05) {
      remaining.addAll(points);
      return remaining;
    }

    if (bestT < 0.90) {
      remaining.add(bestProjPoint);
    }
    for (int j = bestEdgeIdx + 1; j < points.length; j++) {
      remaining.add(points[j]);
    }
    if (remaining.last != points.last) {
      remaining.add(points.last);
    }
    return remaining;
  }
